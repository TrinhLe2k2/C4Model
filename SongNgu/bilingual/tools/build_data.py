#!/usr/bin/env python3
"""Compile reviewed translations/alignment into a classic script usable with file://.

No network access, no changes to the original English files. Python 3.9+ only.
The source snapshot is deliberately explicit. If an original page has changed,
this script fails rather than silently applying translations to different text.
"""
from pathlib import Path
import json, re, hashlib

BASE=Path(__file__).resolve().parents[1]
ROOT=BASE.parent

def normal(s): return re.sub(r'\s+',' ',s).strip()
def plain(s): return re.sub(r'\[\[(\d+)\|([^\]]+)\]\]',lambda m:m[2],s)
def occurrences(text,phrase):
    return [(m.start(),m.end()) for m in re.finditer(r'(?<!\w)'+re.escape(normal(phrase))+r'(?!\w)',text,re.I)]

def build():
    pages=json.loads((BASE/'content/source-snapshot.json').read_text(encoding='utf-8'))
    translations=json.loads((BASE/'content/translations.vi.json').read_text(encoding='utf-8'))
    glossary=json.loads((BASE/'content/glossary.json').read_text(encoding='utf-8'))
    custom=json.loads((BASE/'content/alignment.json').read_text(encoding='utf-8'))
    assert set(translations)=={p['path'] for p in pages},'Every source page must have translations.'
    problems=[];result=[];total_pairs=0;manual_count=0
    for p in pages:
        source=ROOT/p['path']
        raw=source.read_text(encoding='utf-8')
        fragment=re.search(r'<main>([\s\S]*?)</main>',raw)
        if not fragment or fragment.group(1)!=p['raw']:
            raise ValueError(f"English source changed: {p['path']}. Refresh snapshot, translation and alignment explicitly.")
        ts=translations[p['path']]
        assert len(ts)==len(p['units']),(p['path'],len(ts),len(p['units']))
        units=[]
        for i,(u,vi) in enumerate(zip(p['units'],ts)):
            assert isinstance(vi,str) and vi.strip(),(p['path'],i,'Missing translation')
            for n,label in re.findall(r'\[\[(\d+)\|([^\]]+)\]\]',vi):
                assert int(n)<len(u['links']),(p['path'],i,'Invalid link index',n)
            en_text=normal(u['en']);vi_text=normal(plain(vi));pairs=[]
            explicit=custom.get(p['path'],{}).get(str(i),[])
            for x in explicit:
                er=occurrences(en_text,x['en']);vr=[occurrences(vi_text,v) for v in x['vi']]
                ei=x.get('enOccurrence',0);vis=x.get('viOccurrence',[0]*len(vr))
                if len(er)<=ei or any(len(r)<=idx for r,idx in zip(vr,vis)):
                    problems.append({'page':p['path'],'unit':i,'pair':x,'englishMatches':er,'vietnameseMatches':vr});continue
                e=er[ei];vs=[r[idx] for r,idx in zip(vr,vis)]
                note=next((g['note'] for g in glossary if g['en'].lower()==x['en'].lower()),'')
                pairs.append({'en':en_text[e[0]:e[1]],'vi':[vi_text[a:b] for a,b in vs],'eRanges':[e],'vRanges':vs,'note':note,'manual':True})
                manual_count+=1
            for g in sorted(glossary,key=lambda x:len(x['en']),reverse=True):
                ers=occurrences(en_text,g['en'])
                if not ers:continue
                for v in g['vi']:
                    vrs=occurrences(vi_text,v)
                    # Refuse unequal occurrence counts instead of guessing a correspondence.
                    if not vrs or len(vrs)!=len(ers):continue
                    for er,vr in zip(ers,vrs):
                        if any(tuple(q['eRanges'][0])==tuple(er) for q in pairs):continue
                        pairs.append({'en':en_text[er[0]:er[1]],'vi':[vi_text[vr[0]:vr[1]]],'eRanges':[er],'vRanges':[vr],'note':g['note'],'manual':False})
                    break
            for j,pair in enumerate(pairs):pair['id']=str(j)
            total_pairs+=len(pairs)
            units.append({'en':u['en'],'vi':vi,'viText':vi_text,'tag':u['tag'],'links':u['links'],'pairs':pairs})
        result.append({'path':p['path'],'title':p['title'],'raw':p['raw'],'toolsHtml':p['toolsHtml'],'units':units,'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest()})
    if problems:
        (BASE/'content/alignment-errors.json').write_text(json.dumps(problems,ensure_ascii=False,indent=2),encoding='utf-8')
        raise ValueError(f'{len(problems)} authored mappings did not match. See alignment-errors.json.')
    data={'version':1,'source':'Uploaded c4model.zip','pages':result,'glossary':glossary}
    text='/* Generated by tools/build_data.py. Original content: Simon Brown, CC BY 4.0. */\nwindow.C4_READER_DATA = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
    (BASE/'assets/reader-data.js').write_text(text,encoding='utf-8')
    summary={'pages':len(result),'translatedUnits':sum(len(p['units']) for p in result),'phrasePairs':total_pairs,'manualIntroductionPairs':manual_count,'glossaryEntries':len(glossary),'pagesWithoutTranslation':[],'allAuthoredPhraseOffsetsValid':True}
    (BASE/'content/coverage.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(summary,ensure_ascii=False,indent=2))

if __name__=='__main__':build()
